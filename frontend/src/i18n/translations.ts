export const dictionaries = { vi, en };
export type Lang = keyof typeof dictionaries;

/**
 * Dịch NGOÀI React (util/interceptor không gọi được useI18n). Lấy lang hiện tại từ
 * `document.documentElement.lang` (I18nProvider set) → fallback localStorage → 'vi'.
 */
export function translate(key: TranslationKey, vars?: Record<string, string | number>): string {
  let lang: Lang = 'vi';
  if (typeof document !== 'undefined') {
    const d = document.documentElement.lang;
    if (d === 'en' || d === 'vi') lang = d;
    else {
      const s = typeof localStorage !== 'undefined' ? localStorage.getItem('wh-lang') : null;
      if (s === 'en' || s === 'vi') lang = s;
    }
  }
  let str: string = dictionaries[lang][key] ?? dictionaries.vi[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) str = str.replaceAll(`{${k}}`, String(v));
  return str;
}
